#!/usr/bin/env python3
"""Generate docs/game-content-review.md: every needs_review game item, for a clinical reviewer.

Run `python scripts/content_review.py` after editing any content/games/*.json item or a
docs/<game>-source-audit.md quote; `scripts/check.py` fails if the committed pack is stale.
Quotes are copied from the per-game source audits (fetched by the game cards), never invented here.
"""
from pathlib import Path
import json, re, sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import games_data  # noqa: E402

OUT = ROOT / 'docs' / 'game-content-review.md'
TIERS = {1: 'Curious', 2: 'College', 3: 'Mechanism'}
DATA_TEXT = ('post', 'statement', 'card', 'cue', 'claim', 'gap')
SOURCE_HEAD = re.compile(r'^#+\s+Source\s+\[?(\d+)\]?')


def audit_quotes(game: str) -> dict[int, list[dict]]:
    """{source number: [{quote, maps}]} from docs/<game>-source-audit.md blockquotes."""
    path = ROOT / 'docs' / f'{game}-source-audit.md'
    if not path.is_file():
        return {}
    out: dict[int, list[dict]] = {}
    current, in_quote, in_maps = None, False, False
    for line in path.read_text(encoding='utf-8').splitlines():
        head = SOURCE_HEAD.match(line)
        if head or line.startswith('#') or line.startswith('---'):
            in_quote = in_maps = False
            if head:
                current = int(head.group(1))
            elif line.startswith('## '):
                current = None  # a non-source section ends the previous source
            continue
        quotes = out.setdefault(current, []) if current is not None else None
        if line.startswith('>') and quotes is not None:
            text = line.lstrip('>').strip()
            if in_quote:
                quotes[-1]['quote'] += ' ' + text
            else:
                quotes.append({'quote': text, 'maps': ''})
            in_quote, in_maps = True, False
        elif line.startswith('Maps to') and quotes:
            quotes[-1]['maps'] += ' ' + line
            in_quote, in_maps = False, True
        elif in_maps and line.strip() and quotes:
            quotes[-1]['maps'] += ' ' + line
        else:
            in_quote = in_maps = False
    for quotes in out.values():
        for q in quotes:
            q['quote'] = q['quote'].strip().strip('"“”').strip()
    return {k: v for k, v in out.items() if v}


def quotes_for(item_id: str, sid: int, quotes: dict[int, list[dict]]) -> tuple[list[str], bool]:
    """Quotes whose mapping names this item; else every quote from that source (source-level)."""
    pool = quotes.get(sid, [])
    mapped = [q['quote'] for q in pool if re.search(rf'`{re.escape(item_id)}`', q['maps'])]
    return (mapped, True) if mapped else ([q['quote'] for q in pool], False)


def md(text: str) -> str:
    return ' '.join(str(text).split()).replace('|', '\\|')


def render() -> str:
    lessons = [json.loads(p.read_text(encoding='utf-8')) for p in sorted((ROOT / 'content').glob('*.json'))]
    by_slug = {l['slug']: l for l in lessons}
    games = [json.loads(p.read_text(encoding='utf-8')) for p in games_data.game_files(ROOT / 'content' / 'games')
             if not games_data.is_fixture(p)]
    rows = []
    for g in sorted(games, key=lambda g: (g['lesson'], g['game'])):
        for item in g['items']:
            if item['needs_review'] is True:
                rows.append((g, item))
    lines = [
        '# Game content review pack',
        '',
        '<!-- Generated by scripts/content_review.py from content/games/*.json and docs/*-source-audit.md. '
        'Do not hand-edit the item sections; record sign-off in a copy or in a PR that only fills the tables. -->',
        '',
        'For a **qualified clinical reviewer**. Each section below is one game item that is published only as a '
        'flagged preview (`needs_review: true`, shown behind a visible "Pending clinical review" banner) until it is '
        'signed off. The site is educational, not medical advice: no dosing, efficacy figures, product/brand '
        'comparisons or treatment guidance are intended anywhere. Please check that each claim is accurate, stays '
        'within its cited source, and cannot reasonably be read as advice.',
        '',
        'How to sign off: fill the **Decision** row of each item (Approve / Revise: say what / Remove) with your name, '
        'credentials and date, and copy the decision into the summary table. An item leaves preview only when a PR '
        'sets its `needs_review` to `false` and links this signed record. Claim Detective is preview-only by rule '
        '(`scripts/games_data.py`): clearing it also needs that rule changed in the same reviewed PR.',
        '',
        f'**Items awaiting review: {len(rows)}** across {len({g["game"] for g, _ in rows})} games. '
        'Quotes are verbatim from the per-game source audits in `docs/` (fetched live by each game card). '
        '"Source-level quote" means the audit did not map that quote to this item id specifically; '
        'the reviewer should confirm the quote actually supports the item.',
        '',
        '## Summary and sign-off',
        '',
        '| # | Game | Item | Tier | Decision | Reviewer | Date |',
        '|---|---|---|---|---|---|---|',
    ]
    for n, (g, item) in enumerate(rows, 1):
        lines.append(f'| {n} | {g["title"]} | `{item["id"]}` | {item["tier"]} {TIERS[item["tier"]]} |  |  |  |')
    lines.append('')
    current, quotes = None, {}
    for n, (g, item) in enumerate(rows, 1):
        if g['game'] != current:
            current = g['game']
            lesson = by_slug[g['lesson']]
            lines += [f'## {g["title"]}', '',
                      f'Lesson: **{md(lesson["title"])}** (`{g["lesson"]}`). Content: `content/games/{g["game"]}.json`. '
                      f'Audit: `docs/{g["game"]}-source-audit.md`.', '']
            quotes = audit_quotes(g['game'])
        correct = next(c for c in item['choices'] if c['correct'])
        lines += [f'### {n}. `{item["id"]}` — Tier {item["tier"]} ({TIERS[item["tier"]]})', '',
                  f'- **Misconception targeted:** {md(item["misconception"])}',
                  f'- **Prompt:** {md(item["prompt"])}']
        data = item.get('data') or {}
        for key in DATA_TEXT:
            if isinstance(data.get(key), str) and data[key].strip():
                lines.append(f'- **{key.capitalize()} shown:** {md(data[key])}')
        lines += [f'- **Claim taught (correct answer):** {md(correct["text"])}',
                  f'- **Explanation shown:** {md(item["explanation"])}']
        if item.get('worked_example'):
            lines.append(f'- **Worked example:** {md(item["worked_example"])}')
        lines.append(f'- **Why flagged:** {md(item.get("review_note") or g.get("review_note") or "")}')
        lines.append('- **Sources:**')
        for sid in item['source_ids']:
            src = by_slug[g['lesson']]['sources'][sid - 1]
            lines.append(f'  - [{sid}] [{md(src["title"])}]({src["url"]})')
            found, mapped = quotes_for(item['id'], sid, quotes)
            if not found:
                lines.append('    - No verbatim quote recorded in the audit for this source; '
                             'reviewer must verify the claim against the URL.')
            for q in found:
                lines.append(f'    - {"Quote" if mapped else "Source-level quote"}: “{md(q)}”')
        lines += ['', '| Decision (Approve / Revise / Remove) | Reviewer (name, credentials) | Date | Notes |',
                  '|---|---|---|---|', '|  |  |  |  |', '']
    return '\n'.join(lines).rstrip() + '\n'


if __name__ == '__main__':
    OUT.write_text(render(), encoding='utf-8')
    print(f'Wrote {OUT.relative_to(ROOT)}')
